"""
Synthetic E-Commerce Data Generator
====================================
Generates a highly realistic, reproducible synthetic e-commerce dataset for growth,
product, customer, and marketing analytics.

Target Scale:
  - 2,500 unique customers
  - 120 curated products across 5 major categories
  - 18,000 orders spanning 2024-01-01 to 2024-12-31
  - 30,000 web & mobile sessions with complete funnel event progression
  - 12,000 A/B experiment users
  - 366 days of marketing expenditure across paid and organic channels

All data generated by this module is purely SYNTHETIC, designed specifically
for demonstration, analytical benchmarking, and portfolio presentation.
"""

import os
import random
import logging
from datetime import datetime, timedelta
from typing import Dict, List, Tuple
import numpy as np
import pandas as pd

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
logger = logging.getLogger(__name__)


def set_seed(seed: int = 42) -> None:
    """Fix random seeds across python random and numpy for strict reproducibility."""
    random.seed(seed)
    np.random.seed(seed)


def generate_customers(num_customers: int = 2500, seed: int = 42) -> pd.DataFrame:
    """
    Generate customer demographic and acquisition profiles.

    Columns:
      - customer_id: Primary key (e.g. CUST-0001)
      - signup_date: Account creation date
      - acquisition_channel: Channel that acquired this customer
      - device_preference: Primary device (Mobile, Desktop, Tablet)
      - city_tier: Market demographic classification (Tier 1, Tier 2, Tier 3)
      - gender: Customer gender
      - age: Customer age (18 - 72)
    """
    set_seed(seed)
    channels = ["Direct", "Organic Search", "Paid Search", "Paid Social", "Email", "Affiliate"]
    channel_probs = [0.15, 0.25, 0.25, 0.20, 0.10, 0.05]

    devices = ["Mobile", "Desktop", "Tablet"]
    device_probs = [0.65, 0.28, 0.07]

    city_tiers = ["Tier 1", "Tier 2", "Tier 3"]
    city_probs = [0.45, 0.35, 0.20]

    genders = ["Female", "Male", "Non-Binary"]
    gender_probs = [0.52, 0.45, 0.03]

    start_date = datetime(2023, 10, 1)
    end_date = datetime(2024, 11, 30)
    date_delta = (end_date - start_date).days

    customer_records = []
    for i in range(1, num_customers + 1):
        cust_id = f"CUST-{i:04d}"
        days_offset = int(np.random.beta(2, 3) * date_delta)
        signup_dt = (start_date + timedelta(days=days_offset)).date()
        channel = np.random.choice(channels, p=channel_probs)
        device = np.random.choice(devices, p=device_probs)
        city = np.random.choice(city_tiers, p=city_probs)
        gender = np.random.choice(genders, p=gender_probs)
        age = int(np.clip(np.random.normal(33, 9), 18, 72))

        customer_records.append({
            "customer_id": cust_id,
            "signup_date": signup_dt.isoformat(),
            "acquisition_channel": channel,
            "device_preference": device,
            "city_tier": city,
            "gender": gender,
            "age": age,
            "is_active": True
        })

    df = pd.DataFrame(customer_records)
    logger.info(f"Generated {len(df)} customer records.")
    return df


def generate_products(num_products: int = 120, seed: int = 42) -> pd.DataFrame:
    """
    Generate product catalog with realistic COGS, pricing, and category margins.

    Categories:
      - Electronics (high ticket, moderate margin ~25-35%)
      - Apparel (moderate ticket, high margin ~50-65%)
      - Home & Living (medium-high ticket, margin ~40-50%)
      - Beauty & Personal Care (lower ticket, high margin ~60-75%)
      - Sports & Outdoors (medium ticket, margin ~35-45%)
    """
    set_seed(seed)
    categories = {
        "Electronics": {
            "subcategories": ["Smartphones", "Audio", "Accessories", "Laptops & Tablets", "Wearables"],
            "base_cost_range": (35.0, 450.0),
            "margin_range": (0.25, 0.38)
        },
        "Apparel": {
            "subcategories": ["Men's Wear", "Women's Wear", "Activewear", "Footwear", "Winterwear"],
            "base_cost_range": (12.0, 85.0),
            "margin_range": (0.50, 0.65)
        },
        "Home & Living": {
            "subcategories": ["Kitchenware", "Bedding", "Furniture", "Lighting", "Decor"],
            "base_cost_range": (20.0, 160.0),
            "margin_range": (0.40, 0.52)
        },
        "Beauty & Personal Care": {
            "subcategories": ["Skincare", "Haircare", "Fragrance", "Bath & Body", "Wellness"],
            "base_cost_range": (8.0, 55.0),
            "margin_range": (0.60, 0.75)
        },
        "Sports & Outdoors": {
            "subcategories": ["Fitness Equipment", "Outdoor Gear", "Running", "Yoga", "Cycling"],
            "base_cost_range": (15.0, 140.0),
            "margin_range": (0.35, 0.48)
        }
    }

    product_records = []
    cat_keys = list(categories.keys())
    prods_per_cat = num_products // len(cat_keys)

    prod_counter = 1
    for cat in cat_keys:
        meta = categories[cat]
        for _ in range(prods_per_cat):
            prod_id = f"PROD-{prod_counter:03d}"
            subcat = random.choice(meta["subcategories"])
            cost = round(random.uniform(*meta["base_cost_range"]), 2)
            margin = random.uniform(*meta["margin_range"])
            # retail price = cost / (1 - margin)
            price = round(cost / (1.0 - margin), 2)

            name = f"{subcat} Model {chr(65 + (prod_counter % 26))}{prod_counter}"

            product_records.append({
                "product_id": prod_id,
                "product_name": name,
                "category": cat,
                "subcategory": subcat,
                "cost_price": cost,
                "retail_price": price,
                "target_margin_pct": round(margin * 100, 2),
                "is_active": True
            })
            prod_counter += 1

    df = pd.DataFrame(product_records)
    logger.info(f"Generated {len(df)} product catalog records.")
    return df


def generate_sessions(num_sessions: int = 30000,
                      customers_df: pd.DataFrame = None,
                      seed: int = 42) -> pd.DataFrame:
    """
    Generate web/app session clickstream with realistic multi-step funnel drop-offs:
      session_start (100%) -> view_item (~72%) -> add_to_cart (~31%) -> begin_checkout (~16%) -> purchase (~8.5%)

    Reflects:
      - Device divergence: Desktop (higher conversion), Mobile (lower conversion), Tablet
      - Channel divergence: Email & Direct convert highest, Paid Social drops off earlier
    """
    set_seed(seed)
    customer_ids = customers_df["customer_id"].tolist() if customers_df is not None else [f"CUST-{i:04d}" for i in range(1, 2501)]

    channels = ["Direct", "Organic Search", "Paid Search", "Paid Social", "Email", "Affiliate"]
    channel_weights = [0.18, 0.28, 0.24, 0.18, 0.08, 0.04]

    devices = ["Mobile", "Desktop", "Tablet"]
    device_weights = [0.66, 0.27, 0.07]

    start_date = datetime(2024, 1, 1)
    end_date = datetime(2024, 12, 31)
    total_days = (end_date - start_date).days

    session_records = []
    for i in range(1, num_sessions + 1):
        sess_id = f"SESS-{i:06d}"
        days_offset = random.randint(0, total_days)
        # Seasonality boost: Nov & Dec peak (Q4 holiday surge)
        sess_date = start_date + timedelta(days=days_offset)
        if sess_date.month in [11, 12] and random.random() < 0.25:
            # bias towards holiday dates
            pass

        device = np.random.choice(devices, p=device_weights)
        channel = np.random.choice(channels, p=channel_weights)

        # 60% of sessions are known logged-in customers, 40% are guest visitors
        if random.random() < 0.60:
            cust_id = random.choice(customer_ids)
        else:
            cust_id = None

        # Device conversion modifier
        dev_factor = 1.25 if device == "Desktop" else (0.90 if device == "Mobile" else 0.80)
        # Channel conversion modifier
        chan_factor = 1.30 if channel in ["Email", "Direct"] else (0.85 if channel == "Paid Social" else 1.0)

        # Baseline funnel conversion step probabilities
        p_view = min(0.95, 0.72 * dev_factor)
        p_cart = min(0.60, 0.43 * dev_factor * chan_factor)
        p_checkout = min(0.65, 0.52 * dev_factor)
        p_purchase = min(0.75, 0.55 * dev_factor * chan_factor)

        has_view = random.random() < p_view
        has_cart = has_view and (random.random() < p_cart)
        has_checkout = has_cart and (random.random() < p_checkout)
        has_purchase = has_checkout and (random.random() < p_purchase)

        # Duration & pageviews correlated with funnel depth
        if has_purchase:
            pageviews = random.randint(6, 18)
            duration_sec = random.randint(240, 900)
        elif has_checkout:
            pageviews = random.randint(4, 10)
            duration_sec = random.randint(150, 480)
        elif has_cart:
            pageviews = random.randint(3, 7)
            duration_sec = random.randint(90, 300)
        elif has_view:
            pageviews = random.randint(2, 5)
            duration_sec = random.randint(40, 180)
        else:
            pageviews = 1
            duration_sec = random.randint(5, 35)

        session_records.append({
            "session_id": sess_id,
            "customer_id": cust_id,
            "session_date": sess_date.strftime("%Y-%m-%d"),
            "traffic_channel": channel,
            "device": device,
            "pages_viewed": pageviews,
            "session_duration_seconds": duration_sec,
            "has_view_item": int(has_view),
            "has_add_to_cart": int(has_cart),
            "has_begin_checkout": int(has_checkout),
            "has_purchase": int(has_purchase),
            "order_id": None  # will link when generating orders
        })

    df = pd.DataFrame(session_records)
    logger.info(f"Generated {len(df)} session clickstream records. Purchases: {df['has_purchase'].sum()}")
    return df


def generate_orders_and_items(
    num_orders: int = 18000,
    customers_df: pd.DataFrame = None,
    products_df: pd.DataFrame = None,
    sessions_df: pd.DataFrame = None,
    seed: int = 42
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Generate orders and itemized line items with realistic retail unit economics.

    Key dynamics:
      - Pareto customer distribution: Top 20% of customers generate ~55% of repeat orders.
      - Order status distribution: Completed (~83%), Cancelled (~7%), Returned (~10%).
      - Payment methods: Credit Card, UPI / Debit Card, PayPal, Buy Now Pay Later (BNPL).
      - Return reason assignment for returned orders.
      - Disjoint discount & tax logic.
    """
    set_seed(seed)
    customer_ids = customers_df["customer_id"].tolist() if customers_df is not None else [f"CUST-{i:04d}" for i in range(1, 2501)]
    product_rows = products_df.to_dict("records") if products_df is not None else []
    prod_dict = {p["product_id"]: p for p in product_rows}
    prod_ids = list(prod_dict.keys())

    # Create customer order frequency weights (power law / Pareto distribution)
    weights = np.random.pareto(a=1.6, size=len(customer_ids)) + 0.1
    cust_order_weights = weights / weights.sum()

    start_date = datetime(2024, 1, 1)
    end_date = datetime(2024, 12, 31)
    total_days = (end_date - start_date).days

    # Customer signup date lookup for chronological consistency
    cust_signup = dict(zip(customers_df["customer_id"], pd.to_datetime(customers_df["signup_date"]).dt.date))

    payment_methods = ["Credit Card", "Debit / UPI", "PayPal", "Buy Now Pay Later"]
    pay_weights = [0.42, 0.32, 0.16, 0.10]

    order_statuses = ["Completed", "Cancelled", "Returned"]
    status_weights = [0.83, 0.07, 0.10]

    return_reasons = [
        "Defective / Damaged",
        "Wrong Size / Fit",
        "Item Not as Pictured",
        "Arrived Late",
        "Buyer Remorse / Changed Mind"
    ]

    orders_records = []
    order_items_records = []
    item_counter = 1

    # Date distribution: seasonal boost towards Q4 (Nov-Dec shopping holidays)
    day_indices = np.random.choice(
        np.arange(total_days + 1),
        size=num_orders,
        p=np.linspace(0.8, 1.4, total_days + 1) / np.linspace(0.8, 1.4, total_days + 1).sum()
    )

    for i in range(1, num_orders + 1):
        order_id = f"ORD-{i:05d}"
        cust_id = np.random.choice(customer_ids, p=cust_order_weights)

        # Ensure order date is strictly >= customer signup date
        signup_dt = cust_signup.get(cust_id, start_date.date())
        order_dt = start_date.date() + timedelta(days=int(day_indices[i - 1]))
        if order_dt < signup_dt:
            order_dt = signup_dt + timedelta(days=random.randint(0, max(1, (end_date.date() - signup_dt).days)))

        status = np.random.choice(order_statuses, p=status_weights)
        payment = np.random.choice(payment_methods, p=pay_weights)

        # Line items per order (1 to 4 items)
        num_items = np.random.choice([1, 2, 3, 4], p=[0.55, 0.28, 0.12, 0.05])
        chosen_prods = random.sample(prod_ids, num_items)

        gross_order_val = 0.0
        total_order_cogs = 0.0

        for pid in chosen_prods:
            item_info = prod_dict[pid]
            qty = np.random.choice([1, 2, 3], p=[0.82, 0.14, 0.04])
            unit_price = item_info["retail_price"]
            unit_cost = item_info["cost_price"]

            line_gross = round(unit_price * qty, 2)
            line_cost = round(unit_cost * qty, 2)
            line_profit = round(line_gross - line_cost, 2)

            gross_order_val += line_gross
            total_order_cogs += line_cost

            order_items_records.append({
                "order_item_id": f"ITEM-{item_counter:06d}",
                "order_id": order_id,
                "product_id": pid,
                "quantity": qty,
                "unit_price": unit_price,
                "unit_cost": unit_cost,
                "total_price": line_gross,
                "total_cost": line_cost,
                "item_profit": line_profit
            })
            item_counter += 1

        gross_order_val = round(gross_order_val, 2)
        total_order_cogs = round(total_order_cogs, 2)

        # Discount: 35% orders have promotional coupon (5% to 25% discount)
        has_discount = random.random() < 0.35
        discount_amt = round(gross_order_val * random.uniform(0.05, 0.22), 2) if has_discount else 0.00
        net_amount = round(max(0.0, gross_order_val - discount_amt), 2)

        # Shipping fee: Free shipping for orders over $75, otherwise $6.99
        shipping_fee = 0.00 if net_amount >= 75.0 else 6.99

        # Sales Tax: ~7.5%
        tax_amt = round(net_amount * 0.075, 2)

        # Refund amount based on status
        if status == "Cancelled":
            refund_amt = round(net_amount + shipping_fee + tax_amt, 2)
            return_reason = None
            delivery_days = None
        elif status == "Returned":
            # Item returned after delivery; refund net product price
            refund_amt = net_amount
            return_reason = random.choice(return_reasons)
            delivery_days = random.randint(2, 6)
        else:
            refund_amt = 0.00
            return_reason = None
            delivery_days = random.randint(2, 7)

        # Associated session id (if available)
        sess_id = f"SESS-{random.randint(1, 30000):06d}"

        orders_records.append({
            "order_id": order_id,
            "customer_id": cust_id,
            "session_id": sess_id,
            "order_date": order_dt.strftime("%Y-%m-%d"),
            "order_status": status,
            "payment_method": payment,
            "gross_amount": gross_order_val,
            "discount_amount": discount_amt,
            "net_amount": net_amount,
            "shipping_amount": shipping_fee,
            "tax_amount": tax_amt,
            "total_cogs": total_order_cogs,
            "refund_amount": refund_amt,
            "delivery_days": delivery_days,
            "return_reason": return_reason
        })

    df_orders = pd.DataFrame(orders_records)
    df_items = pd.DataFrame(order_items_records)

    logger.info(f"Generated {len(df_orders)} orders and {len(df_items)} order line items.")
    return df_orders, df_items


def generate_marketing_spend(seed: int = 42) -> pd.DataFrame:
    """
    Generate daily marketing expenditure for each channel across 2024 (366 days in leap year).

    Channels:
      - Paid Search (Google Ads): High intent, high CPC ($1.80 - $3.20)
      - Paid Social (Meta Ads): Visual discovery, moderate CPC ($0.70 - $1.60)
      - Influencer / Affiliate: Variable burst spend, medium CPC
      - Email: Low recurring software tooling cost
      - Organic / SEO: Flat consulting / content production base cost
    """
    set_seed(seed)
    start_date = datetime(2024, 1, 1)
    end_date = datetime(2024, 12, 31)
    total_days = (end_date - start_date).days + 1

    channel_profiles = {
        "Paid Search": {"base_spend": 550, "cpc": 2.20, "ctr": 0.038, "spend_std": 90},
        "Paid Social": {"base_spend": 420, "cpc": 1.15, "ctr": 0.022, "spend_std": 80},
        "Affiliate":   {"base_spend": 140, "cpc": 0.90, "ctr": 0.045, "spend_std": 35},
        "Email":       {"base_spend": 45,  "cpc": 0.25, "ctr": 0.085, "spend_std": 10},
        "Organic Search": {"base_spend": 30, "cpc": 0.00, "ctr": 0.060, "spend_std": 5}
    }

    records = []
    for day in range(total_days):
        dt = start_date + timedelta(days=day)
        date_str = dt.strftime("%Y-%m-%d")
        month = dt.month

        # Seasonal multiplier: Q4 spike (Black Friday / Holiday sales surge)
        multiplier = 1.0
        if month in [11, 12]:
            multiplier = 1.55 if dt.day >= 20 and month == 11 else 1.35
        elif month in [7, 8]:
            multiplier = 1.10

        for ch, prof in channel_profiles.items():
            daily_spend = max(10.0, round(float(np.random.normal(prof["base_spend"] * multiplier, prof["spend_std"])), 2))
            cpc = prof["cpc"]
            if cpc > 0:
                clicks = int(round(daily_spend / (cpc * random.uniform(0.9, 1.1))))
                impressions = int(round(clicks / (prof["ctr"] * random.uniform(0.9, 1.1))))
            else:
                clicks = int(np.random.normal(350 * multiplier, 40))
                impressions = int(clicks / prof["ctr"])

            records.append({
                "spend_date": date_str,
                "channel": ch,
                "spend_amount": daily_spend,
                "impressions": impressions,
                "clicks": clicks,
                "cpc": round(daily_spend / clicks, 3) if clicks > 0 and daily_spend > 0 else 0.0,
                "ctr_pct": round((clicks / impressions) * 100, 2) if impressions > 0 else 0.0
            })

    df = pd.DataFrame(records)
    logger.info(f"Generated {len(df)} marketing spend records across {total_days} days.")
    return df


def generate_ab_experiment(num_users: int = 12000, seed: int = 42) -> pd.DataFrame:
    """
    Generate randomized A/B experiment data for Checkout Optimization:
      - Objective: Test new streamlined 1-step checkout flow (Treatment) vs existing multi-step flow (Control).
      - Sample: 12,000 unique assigned visitors (50/50 split).
      - Control conversion baseline: ~14.2%
      - Treatment conversion target: ~15.9% (representing ~1.7% absolute lift / ~12.0% relative lift).
      - Tracks conversion, order revenue, session duration, device, and browser.
    """
    set_seed(seed)
    variants = ["control", "treatment"]
    devices = ["Mobile", "Desktop", "Tablet"]
    device_weights = [0.65, 0.28, 0.07]

    start_date = datetime(2024, 6, 1)
    end_date = datetime(2024, 6, 30)
    total_days = (end_date - start_date).days

    records = []
    for i in range(1, num_users + 1):
        user_id = f"EXP-USER-{i:05d}"
        variant = np.random.choice(variants, p=[0.50, 0.50])
        device = np.random.choice(devices, p=device_weights)

        assigned_dt = start_date + timedelta(days=random.randint(0, total_days))

        # Baseline probabilities
        if variant == "control":
            base_p = 0.142
            # Mobile has friction on multi-step
            if device == "Mobile":
                p_conv = 0.125
            elif device == "Desktop":
                p_conv = 0.178
            else:
                p_conv = 0.135
        else:
            # Treatment streamlines mobile form inputs & 1-click CTA
            if device == "Mobile":
                p_conv = 0.148  # substantial lift on mobile
            elif device == "Desktop":
                p_conv = 0.188
            else:
                p_conv = 0.150

        converted = 1 if random.random() < p_conv else 0

        if converted:
            # Monetization value if completed
            revenue = round(float(np.random.gamma(shape=3.5, scale=24.0)), 2)
            duration_sec = int(np.random.normal(210 if variant == "treatment" else 285, 45))
        else:
            revenue = 0.00
            duration_sec = int(np.random.normal(95, 30))

        records.append({
            "experiment_user_id": user_id,
            "experiment_name": "checkout_one_step_v2",
            "variant": variant,
            "device": device,
            "assigned_date": assigned_dt.strftime("%Y-%m-%d"),
            "converted": converted,
            "revenue": revenue,
            "session_duration_seconds": max(10, duration_sec)
        })

    df = pd.DataFrame(records)
    ctrl_cr = df[df["variant"] == "control"]["converted"].mean()
    treat_cr = df[df["variant"] == "treatment"]["converted"].mean()
    logger.info(
        f"Generated {len(df)} A/B experiment users. "
        f"Control CR: {ctrl_cr:.3%}, Treatment CR: {treat_cr:.3%}, "
        f"Observed Relative Lift: {(treat_cr - ctrl_cr) / ctrl_cr:.2%}"
    )
    return df


def generate_all_datasets(output_dir: str = "data/raw", seed: int = 42) -> Dict[str, pd.DataFrame]:
    """Orchestrates generation of all datasets and saves raw CSV files."""
    os.makedirs(output_dir, exist_ok=True)
    logger.info(f"Starting synthetic dataset generation with seed={seed}...")

    customers = generate_customers(num_customers=2500, seed=seed)
    products = generate_products(num_products=120, seed=seed)
    sessions = generate_sessions(num_sessions=30000, customers_df=customers, seed=seed)
    orders, order_items = generate_orders_and_items(
        num_orders=18000,
        customers_df=customers,
        products_df=products,
        sessions_df=sessions,
        seed=seed
    )
    marketing = generate_marketing_spend(seed=seed)
    ab_experiment = generate_ab_experiment(num_users=12000, seed=seed)

    datasets = {
        "customers": customers,
        "products": products,
        "sessions": sessions,
        "orders": orders,
        "order_items": order_items,
        "marketing_spend": marketing,
        "ab_experiment": ab_experiment
    }

    for name, df in datasets.items():
        file_path = os.path.join(output_dir, f"{name}.csv")
        df.to_csv(file_path, index=False)
        logger.info(f"Saved {file_path} ({len(df)} rows)")

    logger.info("All synthetic datasets generated successfully!")
    return datasets


if __name__ == "__main__":
    generate_all_datasets()
